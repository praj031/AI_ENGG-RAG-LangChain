import asyncio
import os

from dotenv import load_dotenv
from ollama import AsyncClient


load_dotenv()


class ChatService:

    def __init__(self):
        api_key = os.environ["OLLAMA_API_KEY"]
        self.model = os.getenv("OLLAMA_MODEL", "kimi-k2.7-code:cloud")

        self.client = AsyncClient(
            host="https://ollama.com",
            headers={"Authorization": f"Bearer {api_key}"}
        )

    async def stream(self, question: str):
        stream = await self.client.chat(
            model=self.model,
            messages=[
                {
                    "role": "user",
                    "content": question,
                }
            ],
            stream=True,
        )

        async for chunk in stream:
            # Text generated by the model
            if chunk.message and chunk.message.content:
                yield {
                    "type": "content",
                    "content": chunk.message.content,
                }

            # Ollama returns token counts in the final chunk when done
            if chunk.done:
                prompt_tokens = getattr(chunk, "prompt_eval_count", 0) or 0
                completion_tokens = getattr(chunk, "eval_count", 0) or 0

                yield {
                    "type": "usage",
                    "usage": {
                        "prompt_tokens": prompt_tokens,
                        "completion_tokens": completion_tokens,
                        "total_tokens": prompt_tokens + completion_tokens,
                    },
                }


async def main():
    chat_service = ChatService()

    query = input("Query: ")

    print("Assistant: ", end="", flush=True)

    async for event in chat_service.stream(query):
        if event["type"] == "content":
            print(event["content"], end="", flush=True)

        elif event["type"] == "usage":
            usage = event["usage"]

            print("\n")
            print("Usage:")
            print(f"  Prompt tokens:     {usage['prompt_tokens']}")
            print(f"  Completion tokens: {usage['completion_tokens']}")
            print(f"  Total tokens:      {usage['total_tokens']}")

    print()


if __name__ == "__main__":
    asyncio.run(main())
